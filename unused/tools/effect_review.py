"""NOT IN USE: unfinished idea (the global Effects search), potentially scrapped. It is not linked from the site and update.py does not run it. See data/EFFECT_SEARCH_NOT_IN_USE.md.

Writes data/effect_tags_review.md: the effects the tagger could not place, and sentences that may be effects with another wording."""
import sys, re, collections
sys.stdout.reconfigure(encoding='utf8')
sys.path.insert(0, __file__.replace(chr(92), '/').rsplit('/', 1)[0])
import effect_tags as E

res, unsplit, stale = E.tag_all()
bad = collections.defaultdict(list)
for k, v in res.items():
    for e in v['effects']:
        q = [t for t in e['x'] + e['y'] if t.startswith('?')]
        if q and not re.match(r'\?(ruby|gem) power', q[0]): bad[q[0][1:]].append((v['name'], k, e))
L = ['# NOT IN USE: unfinished idea (the global Effects search), potentially scrapped. It is not linked from the site and update.py does not run it. See data/EFFECT_SEARCH_NOT_IN_USE.md.\n', '# Effects the tagger could not place (for review)\n',
     'Generated by `tools/effect_review.py`. Corrections go into `data/effect_tags_fixes.json`. Answer by writing the stat next to each line, or "skip" for a non-effect.\n',
     '## 1. Stats it did not recognise (%d effects)\n' % sum(len(v) for v in bad.values())]
for t, items in sorted(bad.items(), key=lambda x: -len(x[1])):
    L.append(f'- **{t}** ({len(items)}x)')
    seen = set()
    for name, k, e in items:
        if (name, e['text']) in seen: continue
        seen.add((name, e['text']))
        side = 'X' if any(x.startswith('?') for x in e['x']) else 'Y'
        L.append(f'  - {name} [{side}]: {e["text"][:150]}')
        if len(seen) >= 3: break
FLAVOR = re.compile(r'Quest|Preferably')
cand = collections.OrderedDict()
for k, q in unsplit:
    if re.search(r'based on|more|improved|worth|per |increases|grow|multiplied|gain|collect|generate|give', q, re.I) and len(q) < 260 and not FLAVOR.search(res[k]['name'] if k in res else k):
        cand.setdefault(q, []).append(res[k]['name'] if k in res else k)
L.append('\n## 2. Sentences that may be effects but have no "Increase X" wording (%d)\n' % len(cand))
for q, ns in cand.items():
    L.append(f'- {q[:170]}  ({", ".join(sorted(set(ns))[:3])}{"..." if len(set(ns)) > 3 else ""})')
if stale:
    L.append('\n## 3. Hand corrections that no longer fit (the sentence changed or is gone): %d\n' % len(stale))
    for f in stale: L.append('- %s: %s' % (f['key'], f['text'][:160]))
open(E.R + 'data/effect_tags_review.md', 'w', encoding='utf8').write('\n'.join(L) + '\n')
print(len(bad), len(cand))
